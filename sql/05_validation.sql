-- SECTION 2: DATA QUALITY CHECKS (run after backfill with real API keys)
-- =============================================================================

-- 2.1  EIA Prices — expect ~750 trading days/3yrs, 5 distinct series
SELECT
    'FACT_EIA_PRICES' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT SERIES_ID) AS DISTINCT_SERIES,
    COUNT(DISTINCT PRICE_DATE) AS DISTINCT_DATES,
    MIN(PRICE_DATE) AS MIN_DATE,
    MAX(PRICE_DATE) AS MAX_DATE,
    ROUND(AVG(PRICE_USD), 2) AS AVG_PRICE,
    SUM(CASE WHEN PRICE_USD IS NULL OR PRICE_USD <= 0 THEN 1 ELSE 0 END) AS INVALID_PRICES
FROM APERTURE_DB.ENERGY.FACT_EIA_PRICES;

-- 2.2  EIA Prices — per-series coverage check
SELECT
    SERIES_ID,
    COUNT(*) AS ROW_COUNT,
    MIN(PRICE_DATE) AS MIN_DATE,
    MAX(PRICE_DATE) AS MAX_DATE,
    ROUND(MIN(PRICE_USD), 2) AS MIN_PRICE,
    ROUND(MAX(PRICE_USD), 2) AS MAX_PRICE,
    ROUND(AVG(PRICE_USD), 2) AS AVG_PRICE
FROM APERTURE_DB.ENERGY.FACT_EIA_PRICES
GROUP BY SERIES_ID
ORDER BY SERIES_ID;

-- 2.3  EIA Inventory — expect weekly data, 6 PADDs, multiple product series
SELECT
    'FACT_EIA_INVENTORY' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT SERIES_ID) AS DISTINCT_SERIES,
    COUNT(DISTINCT PADD_ID) AS DISTINCT_PADDS,
    COUNT(DISTINCT REPORT_DATE) AS DISTINCT_DATES,
    MIN(REPORT_DATE) AS MIN_DATE,
    MAX(REPORT_DATE) AS MAX_DATE,
    SUM(CASE WHEN INVENTORY_THOUSAND_BARRELS IS NULL THEN 1 ELSE 0 END) AS NULL_INVENTORY
FROM APERTURE_DB.ENERGY.FACT_EIA_INVENTORY;

-- 2.4  EIA Inventory — per-PADD breakdown
SELECT
    p.PADD_CODE,
    COUNT(*) AS ROW_COUNT,
    COUNT(DISTINCT i.SERIES_ID) AS SERIES_COUNT,
    MIN(i.REPORT_DATE) AS MIN_DATE,
    MAX(i.REPORT_DATE) AS MAX_DATE
FROM APERTURE_DB.ENERGY.FACT_EIA_INVENTORY i
JOIN APERTURE_DB.ENERGY.DIM_PADD_REGIONS p ON i.PADD_ID = p.PADD_ID
GROUP BY p.PADD_CODE
ORDER BY p.PADD_CODE;

-- 2.5  NOAA Weather — expect daily data, 5 PADDs (no US total)
SELECT
    'FACT_NOAA_WEATHER' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT PADD_ID) AS DISTINCT_PADDS,
    COUNT(DISTINCT OBSERVATION_DATE) AS DISTINCT_DATES,
    MIN(OBSERVATION_DATE) AS MIN_DATE,
    MAX(OBSERVATION_DATE) AS MAX_DATE,
    ROUND(AVG(AVG_TEMP_F), 1) AS OVERALL_AVG_TEMP,
    SUM(CASE WHEN AVG_TEMP_F < -50 OR AVG_TEMP_F > 130 THEN 1 ELSE 0 END) AS OUTLIER_TEMPS
FROM APERTURE_DB.ENERGY.FACT_NOAA_WEATHER;

-- 2.6  NOAA Weather — HDD/CDD sanity check (should be non-negative, sum > 0)
SELECT
    p.PADD_CODE,
    COUNT(*) AS OBSERVATIONS,
    ROUND(AVG(w.HEATING_DEGREE_DAYS), 2) AS AVG_HDD,
    ROUND(AVG(w.COOLING_DEGREE_DAYS), 2) AS AVG_CDD,
    SUM(CASE WHEN w.HEATING_DEGREE_DAYS < 0 THEN 1 ELSE 0 END) AS NEGATIVE_HDD,
    SUM(CASE WHEN w.COOLING_DEGREE_DAYS < 0 THEN 1 ELSE 0 END) AS NEGATIVE_CDD
FROM APERTURE_DB.ENERGY.FACT_NOAA_WEATHER w
JOIN APERTURE_DB.ENERGY.DIM_PADD_REGIONS p ON w.PADD_ID = p.PADD_ID
GROUP BY p.PADD_CODE
ORDER BY p.PADD_CODE;

-- 2.7  GDELT Events — expect weekly data, 20 countries, tension 0-10
SELECT
    'FACT_GDELT_EVENTS' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT COUNTRY_CODE) AS DISTINCT_COUNTRIES,
    COUNT(DISTINCT EVENT_DATE) AS DISTINCT_DATES,
    MIN(EVENT_DATE) AS MIN_DATE,
    MAX(EVENT_DATE) AS MAX_DATE,
    ROUND(AVG(GEOPOLITICAL_TENSION_SCORE), 2) AS AVG_TENSION,
    SUM(CASE WHEN GEOPOLITICAL_TENSION_SCORE < 0 OR GEOPOLITICAL_TENSION_SCORE > 10 THEN 1 ELSE 0 END) AS OUT_OF_RANGE
FROM APERTURE_DB.ENERGY.FACT_GDELT_EVENTS;

-- 2.8  GDELT — country distribution and PADD mapping coverage
SELECT
    g.COUNTRY_CODE,
    m.COUNTRY_NAME,
    m.PRIMARY_PADD_IMPACT,
    COUNT(*) AS EVENT_ROWS,
    ROUND(AVG(g.GEOPOLITICAL_TENSION_SCORE), 2) AS AVG_TENSION
FROM APERTURE_DB.ENERGY.FACT_GDELT_EVENTS g
LEFT JOIN APERTURE_DB.ENERGY.DIM_GDELT_COUNTRY_PADD_MAP m ON g.COUNTRY_CODE = m.COUNTRY_CODE
GROUP BY g.COUNTRY_CODE, m.COUNTRY_NAME, m.PRIMARY_PADD_IMPACT
ORDER BY EVENT_ROWS DESC;

-- 2.9  EIA STEO Forecasts — expect monthly data, 9 series
SELECT
    'FACT_EIA_STEO_FORECASTS' AS TABLE_NAME,
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT SERIES_ID) AS DISTINCT_SERIES,
    COUNT(DISTINCT FORECAST_MONTH) AS DISTINCT_MONTHS,
    MIN(FORECAST_MONTH) AS MIN_MONTH,
    MAX(FORECAST_MONTH) AS MAX_MONTH,
    SUM(CASE WHEN FORECAST_VALUE IS NULL THEN 1 ELSE 0 END) AS NULL_FORECASTS
FROM APERTURE_DB.ENERGY.FACT_EIA_STEO_FORECASTS;

-- 2.10 STEO — per-series breakdown
SELECT
    SERIES_ID,
    COUNT(*) AS ROW_COUNT,
    MIN(FORECAST_MONTH) AS MIN_MONTH,
    MAX(FORECAST_MONTH) AS MAX_MONTH,
    ROUND(MIN(FORECAST_VALUE), 2) AS MIN_VALUE,
    ROUND(MAX(FORECAST_VALUE), 2) AS MAX_VALUE
FROM APERTURE_DB.ENERGY.FACT_EIA_STEO_FORECASTS
GROUP BY SERIES_ID
ORDER BY SERIES_ID;


-- =============================================================================
-- SECTION 3: MART VIEW SAMPLE QUERIES (Tableau VizQL patterns)
-- =============================================================================

-- 3.1  WTI Price trend (last 90 days)
SELECT PRICE_DATE, WTI_PRICE_USD, WTI_DAILY_CHANGE, WTI_BRENT_SPREAD
FROM APERTURE_DB.ENERGY.MART_EIA_PRICES
WHERE PRICE_DATE >= DATEADD(DAY, -90, CURRENT_DATE())
ORDER BY PRICE_DATE DESC
LIMIT 500;

-- 3.2  Inventory by PADD (latest 12 weeks)
SELECT REPORT_DATE, PADD_CODE, PADD_NAME,
       CRUDE_INVENTORY_KBBL, CRUDE_WEEKLY_CHANGE_KBBL,
       TOTAL_PETROLEUM_INVENTORY_KBBL
FROM APERTURE_DB.ENERGY.MART_EIA_INVENTORY
WHERE PADD_ID IN (1,2,3,4,5)
  AND REPORT_DATE >= DATEADD(WEEK, -12, CURRENT_DATE())
ORDER BY REPORT_DATE DESC, PADD_ID
LIMIT 500;

-- 3.3  Heating Degree Days (PADD 1 + PADD 2, last winter)
SELECT OBSERVATION_DATE, PADD_CODE, PADD_NAME,
       AVG_TEMP_F, HEATING_DEGREE_DAYS, COOLING_DEGREE_DAYS
FROM APERTURE_DB.ENERGY.MART_WEATHER
WHERE PADD_ID IN (1, 2)
  AND MONTH_NUM IN (11, 12, 1, 2, 3)
  AND OBSERVATION_DATE >= DATEADD(YEAR, -1, CURRENT_DATE())
ORDER BY OBSERVATION_DATE DESC
LIMIT 500;

-- 3.4  Geopolitical tension by country (top 10 most active)
SELECT COUNTRY_CODE, COUNTRY_NAME, ENERGY_RELEVANCE, PRIMARY_PADD_IMPACT,
       COUNT(*) AS WEEKS_OBSERVED,
       ROUND(AVG(GEOPOLITICAL_TENSION_SCORE), 2) AS AVG_TENSION,
       SUM(CONFLICT_EVENT_COUNT) AS TOTAL_CONFLICTS,
       SUM(COOPERATION_EVENT_COUNT) AS TOTAL_COOPERATION
FROM APERTURE_DB.ENERGY.MART_GEOPOLITICAL
WHERE EVENT_DATE >= DATEADD(YEAR, -1, CURRENT_DATE())
GROUP BY COUNTRY_CODE, COUNTRY_NAME, ENERGY_RELEVANCE, PRIMARY_PADD_IMPACT
ORDER BY AVG_TENSION DESC
LIMIT 10;

-- 3.5  STEO Forecast trend (last 2 years)
SELECT FORECAST_MONTH, MONTH_NAME, YEAR_NUM,
       STEO_WTI_FORECAST, STEO_BRENT_FORECAST,
       STEO_PRODUCTION_FORECAST, STEO_CONSUMPTION_FORECAST
FROM APERTURE_DB.ENERGY.MART_EIA_STEO
WHERE FORECAST_MONTH >= DATEADD(YEAR, -2, CURRENT_DATE())
ORDER BY FORECAST_MONTH DESC;

-- 3.6  Row counts per mart (sanity check — rows should equal distinct keys)
SELECT 'MART_EIA_PRICES' AS MART, COUNT(*) AS TOTAL_ROWS
FROM APERTURE_DB.ENERGY.MART_EIA_PRICES
