SELECT 'MART_EIA_STEO', COUNT(*)
FROM APERTURE_DB.ENERGY.MART_EIA_STEO
UNION ALL
SELECT 'MART_WEATHER', COUNT(*)
FROM APERTURE_DB.ENERGY.MART_WEATHER
UNION ALL
SELECT 'MART_GEOPOLITICAL', COUNT(*)
FROM APERTURE_DB.ENERGY.MART_GEOPOLITICAL
ORDER BY MART;


