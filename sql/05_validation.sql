-- SECTION 4: PIPELINE MONITORING QUERIES
-- =============================================================================

-- 4.1  Pipeline log — latest runs per procedure
SELECT
    PROCEDURE_NAME,
    MAX(RUN_STARTED_AT) AS LAST_RUN,
    MAX(CASE WHEN STATUS = 'SUCCESS' THEN RUN_STARTED_AT END) AS LAST_SUCCESS,
    MAX(CASE WHEN STATUS = 'ERROR' THEN RUN_STARTED_AT END) AS LAST_ERROR,
    COUNT(*) AS TOTAL_RUNS,
    SUM(CASE WHEN STATUS = 'SUCCESS' THEN 1 ELSE 0 END) AS SUCCESS_COUNT,
    SUM(CASE WHEN STATUS = 'ERROR' THEN 1 ELSE 0 END) AS ERROR_COUNT,
    SUM(CASE WHEN STATUS = 'SKIPPED' THEN 1 ELSE 0 END) AS SKIPPED_COUNT
FROM APERTURE_DB.ENERGY.PIPELINE_LOG
GROUP BY PROCEDURE_NAME
ORDER BY LAST_RUN DESC;

-- 4.2  Pipeline log — recent errors (last 7 days)
SELECT PROCEDURE_NAME, RUN_STARTED_AT, STATUS, ROWS_AFFECTED, ERROR_MESSAGE
FROM APERTURE_DB.ENERGY.PIPELINE_LOG
WHERE STATUS = 'ERROR'
  AND RUN_STARTED_AT >= DATEADD(DAY, -7, CURRENT_TIMESTAMP())
ORDER BY RUN_STARTED_AT DESC
LIMIT 50;

-- 4.3  Pipeline log — full history (last 30 days)
SELECT PROCEDURE_NAME, RUN_STARTED_AT, RUN_ENDED_AT, STATUS,
       ROWS_AFFECTED,
       DATEDIFF(SECOND, RUN_STARTED_AT, RUN_ENDED_AT) AS DURATION_SECONDS,
       ERROR_MESSAGE
FROM APERTURE_DB.ENERGY.PIPELINE_LOG
WHERE RUN_STARTED_AT >= DATEADD(DAY, -30, CURRENT_TIMESTAMP())
ORDER BY RUN_STARTED_AT DESC;

-- 4.4  Data freshness check — how current is each source?
SELECT
    'EIA Prices' AS SOURCE,
    MAX(PRICE_DATE) AS LATEST_DATE,
    DATEDIFF(DAY, MAX(PRICE_DATE), CURRENT_DATE()) AS DAYS_STALE
FROM APERTURE_DB.ENERGY.FACT_EIA_PRICES
UNION ALL
SELECT 'EIA Inventory', MAX(REPORT_DATE), DATEDIFF(DAY, MAX(REPORT_DATE), CURRENT_DATE())
FROM APERTURE_DB.ENERGY.FACT_EIA_INVENTORY
UNION ALL
SELECT 'NOAA Weather', MAX(OBSERVATION_DATE), DATEDIFF(DAY, MAX(OBSERVATION_DATE), CURRENT_DATE())
FROM APERTURE_DB.ENERGY.FACT_NOAA_WEATHER
UNION ALL
SELECT 'GDELT Events', MAX(EVENT_DATE), DATEDIFF(DAY, MAX(EVENT_DATE), CURRENT_DATE())
FROM APERTURE_DB.ENERGY.FACT_GDELT_EVENTS
UNION ALL
SELECT 'EIA STEO', MAX(FORECAST_MONTH), DATEDIFF(DAY, MAX(FORECAST_MONTH), CURRENT_DATE())
FROM APERTURE_DB.ENERGY.FACT_EIA_STEO_FORECASTS;

